package io.github.rualert.mynotesapp.data.auth

/**
 * Реакция на конец сессии: выход из аккаунта или сессия, которую сервер
 * больше не продлевает (`401` на `/Auth/refresh`).
 *
 * Сессия о заметках ничего не знает — порт объявлен здесь, а реализует его
 * тот, кому есть что забыть. Так же устроен `IUserRegistrationHandler` на
 * сервере: зависимость направлена от заметок к сессии, а не наоборот.
 *
 * Вызов **не должен ждать** работы, которую делает: конец сессии бывает
 * обнаружен посреди отправки заметок (её запрос получил `401`), и ожидание,
 * пока отправка закончится, изнутри самой отправки — взаимная блокировка.
 */
fun interface SessionEndListener {
    fun onSessionEnded()
}
