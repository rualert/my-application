namespace MyApplication.Application.Notes;

/// <summary>
///     Содержимое приветственной заметки, которую получает каждый новый
///     пользователь (см. <see cref="WelcomeNoteRegistrationHandler"/>). Текст —
///     Markdown: в режиме просмотра интерфейс рендерит его с форматированием.
/// </summary>
public static class WelcomeNote
{
    public const string Title = "Добро пожаловать";

    // Окончания строк приводим к \n: иначе текст зависел бы от того, с какими
    // окончаниями файл лежит на диске (Windows-checkout или Linux-сборка образа).
    public static readonly string Text = """
        # Добро пожаловать, кожаные мешки!

        Это эксперимент: проверка того, можно ли с помощью ИИ написать что-то полезное.
        Всё — от кода до деплоя — сделано без непосредственного участия человека.
        Исходный код: [github.com/rualert/my-application](https://github.com/rualert/my-application)

        ## Что умеет приложение

        - **Заметки** — создавайте, редактируйте, удаляйте. Они приватны: видны только вам.
        - **Автосохранение** — правки сохраняются сами, кнопки «Сохранить» нет.
        - **Markdown** — в режиме просмотра заметка отображается с форматированием.
        - **Поиск** — по заголовкам и тексту, находит даже с опечаткой.

        ## Горячие клавиши

        Приложением можно пользоваться целиком с клавиатуры, не касаясь мыши. Полный список — по `Ctrl` + `/`.

        - Из любого места: `Shift` `Shift` — курсор в поле поиска, `Alt` + `N` — создать заметку, `Ctrl` + `E` — режим просмотра или редактирования, `Ctrl` + `\` — свернуть или развернуть список.
        - В поиске: `↑` `↓` — перемещение по результатам, `Enter` — открыть заметку, повторный `Enter` — начать её редактировать, `Esc` — очистить запрос, повторный `Esc` — вернуться туда, откуда пришли.
        - В списке заметок: `↑` `↓` — перемещение по заметкам, `Enter` — курсор в текст заметки, `Delete` — удалить её.
        - В редакторе: `Esc` — вернуться в список. В заголовке: `Enter` или `↓` — курсор в начало текста. В начале текста: `↑` — обратно в конец заголовка.
        """.ReplaceLineEndings("\n");
}
