// Общая конфигурация для всех сценариев нагрузочного тестирования.

// Адрес API. По умолчанию — порт, который публикует ci/docker-compose.app.yml
// на хосте. Переопределяется переменной окружения BASE_URL (например,
// http://myapplication-api:8080, если сам k6 запущен контейнером в сети `elastic`).
export const BASE_URL = __ENV.BASE_URL || 'http://localhost:8080';

// Сколько заметок создать перед стартом нагрузки (setup()), чтобы сценарии
// работали не с пустой/вырожденной базой, а с реалистичным объёмом данных.
export const SEED_COUNT = Number(__ENV.SEED_COUNT || 50);

// Ступени роста RPS: k6 держит каждую ступень заданное время, дальше
// поднимает целевой RPS. Цель — найти ступень, на которой сервис перестаёт
// укладываться в пороги (см. `thresholds` в каждом сценарии): это и есть
// максимальный RPS, который сервис держит. Переопределяются переменными
// окружения, если нужно погонять тест быстрее/на других значениях, например:
// STAGE_DURATION=10s STAGE_TARGETS=50,100,200 k6 run scenarios/notes-list.js
const stageDuration = __ENV.STAGE_DURATION || '30s';
const stageTargets = (__ENV.STAGE_TARGETS || '50,100,200,400,800,1200')
    .split(',')
    .map(Number);

export const RAMP_STAGES = stageTargets.map((target) => ({ target, duration: stageDuration }));

// Верхняя граница числа VU, которые k6 может выделить, чтобы удержать
// целевой RPS при росте латентности. Если это станет узким местом раньше,
// чем сервис реально упрётся в потолок, увеличьте через переменную окружения.
export const MAX_VUS = Number(__ENV.MAX_VUS || 2000);
